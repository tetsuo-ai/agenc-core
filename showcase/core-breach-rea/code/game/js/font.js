export const FONT_H = 7;
export const FONT_W = 5;

export function drawText(put, x, y, text, color, scale = 1) {
  let cx = x;
  const s = String(text).toUpperCase();
  for (let i = 0; i < s.length; i++) {
    const ch = s[i];
    if (ch === "\n") { cx = x; y += (FONT_H + 2) * scale; continue; }
    const g = F[ch] || F["?"];
    for (let row = 0; row < 7; row++) {
      const bits = g[row];
      for (let col = 0; col < 5; col++) {
        if (bits & (1 << (4 - col))) {
          for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) {
            put(cx + col * scale + sx, y + row * scale + sy, color);
          }
        }
      }
    }
    cx += (FONT_W + 1) * scale;
  }
  return cx;
}
export function textWidth(text, scale = 1) {
  let w = 0, max = 0;
  for (const ch of String(text)) {
    if (ch === "\n") { max = Math.max(max, w); w = 0; }
    else w += (FONT_W + 1) * scale;
  }
  return Math.max(max, w);
}
