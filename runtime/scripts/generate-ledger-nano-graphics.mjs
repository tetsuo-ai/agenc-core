#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";

import sharp from "sharp";

const runtimeRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = join(
  runtimeRoot,
  "src",
  "tui",
  "components",
  "ledgerNanoGraphics.generated.ts",
);
const rasterWidth = 320;
const rasterHeight = 160;
const rasterHalfWidth = rasterWidth / 2;
const previewWidth = 72;
const previewHeight = 40;

const sources = [
  {
    name: "LEDGER_NANO",
    path: join(runtimeRoot, "assets", "ledger-nano.svg"),
  },
  {
    name: "LEDGER_NANO_VERIFIED",
    path: join(runtimeRoot, "assets", "ledger-nano-verified.svg"),
  },
];

const brailleDots = [
  [0, 0, 1],
  [0, 1, 2],
  [0, 2, 4],
  [1, 0, 8],
  [1, 1, 16],
  [1, 2, 32],
  [0, 3, 64],
  [1, 3, 128],
];

function brailleLines(raw) {
  const lines = [];
  for (let y = 0; y < previewHeight; y += 4) {
    let line = "";
    for (let x = 0; x < previewWidth; x += 2) {
      let bits = 0;
      for (const [dx, dy, bit] of brailleDots) {
        const offset = ((y + dy) * previewWidth + x + dx) * 4;
        const visible =
          raw[offset + 3] > 48 &&
          Math.max(raw[offset], raw[offset + 1], raw[offset + 2]) > 128;
        if (visible) bits |= bit;
      }
      line += String.fromCodePoint(0x2800 + bits);
    }
    lines.push(line.replace(/[\u2800 ]+$/u, ""));
  }
  const first = lines.findIndex(Boolean);
  const last = lines.findLastIndex(Boolean);
  return first === -1 ? [""] : lines.slice(first, last + 1);
}

function verticalHalf(raw, startX) {
  const rowBytes = rasterWidth * 4;
  const halfRowBytes = rasterHalfWidth * 4;
  const result = Buffer.allocUnsafe(halfRowBytes * rasterHeight);
  for (let row = 0; row < rasterHeight; row += 1) {
    raw.copy(
      result,
      row * halfRowBytes,
      row * rowBytes + startX * 4,
      row * rowBytes + startX * 4 + halfRowBytes,
    );
  }
  return result;
}

const chunks = [
  "// Generated by runtime/scripts/generate-ledger-nano-graphics.mjs.",
  "// Source of truth: runtime/assets/ledger-nano*.svg.",
  "// Kitty receives these zlib-compressed RGBA rasters directly.",
  "",
  `export const LEDGER_NANO_RASTER_WIDTH = ${rasterWidth}`,
  `export const LEDGER_NANO_RASTER_HEIGHT = ${rasterHeight}`,
  `export const LEDGER_NANO_RASTER_HALF_WIDTH = ${rasterHalfWidth}`,
];

for (const source of sources) {
  const svg = await readFile(source.path);
  const rgba = await sharp(svg)
    .resize(rasterWidth, rasterHeight, { fit: "fill" })
    .ensureAlpha()
    .raw()
    .toBuffer();
  const preview = await sharp(svg)
    .resize(previewWidth, previewHeight, { fit: "fill" })
    .ensureAlpha()
    .raw()
    .toBuffer();
  const compressedLeft = deflateSync(verticalHalf(rgba, 0), {
    level: 9,
  }).toString("base64");
  const compressedRight = deflateSync(verticalHalf(rgba, rasterHalfWidth), {
    level: 9,
  }).toString("base64");

  chunks.push(
    "",
    `export const ${source.name}_BRAILLE_LINES = [`,
    ...brailleLines(preview).map((line) => `  ${JSON.stringify(line)},`),
    "] as const",
    "",
    `export const ${source.name}_LEFT_RGBA_ZLIB_BASE64 =`,
    `  ${JSON.stringify(compressedLeft)}`,
    "",
    `export const ${source.name}_RIGHT_RGBA_ZLIB_BASE64 =`,
    `  ${JSON.stringify(compressedRight)}`,
  );
}

await writeFile(outputPath, `${chunks.join("\n")}\n`, "utf8");
