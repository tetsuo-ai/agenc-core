#!/usr/bin/env node

import { randomUUID } from "node:crypto";
import { lstat, open, readFile, rename, unlink } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { renderSdkWireTypes } from "./sdk-wire-types.mjs";
import { checkSdkWireParity } from "./check-sdk-wire-parity.mjs";
import {
  createSourceFile,
  isInterfaceDeclaration,
  ScriptTarget,
} from "typescript";

const runtimeRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const paths = {
  schemas: "src/entrypoints/sdk/coreSchemas.ts",
  coreTypes: "src/entrypoints/sdk/coreTypes.ts",
  generated: "src/entrypoints/sdk/coreTypes.generated.ts",
  runtimeProtocol: "src/app-server/protocol/index.ts",
  packageTranscriptV2: "../packages/agenc-sdk/src/transcript-v2.generated.ts",
  packageWire: "../packages/agenc-sdk/src/protocol-wire.generated.ts",
  packageWorkflowResult:
    "../packages/agenc-sdk/src/workflow-result.generated.ts",
};
const checkCommand =
  "npm --workspace=@tetsuo-ai/runtime run check:sdk-generated-types";

async function readRuntimeFile(relativePath) {
  return readFile(path.join(runtimeRoot, relativePath), "utf8");
}

function countMatches(source, pattern) {
  return source.match(pattern)?.length ?? 0;
}

function expectCondition(failures, condition, message) {
  if (!condition) {
    failures.push(message);
  }
}

function normalizeLineEndings(source) {
  return source.replace(/\r\n?/g, "\n");
}

export function parseSdkGeneratedTypesMode(args) {
  if (args.length === 0) return "check";
  if (args.length === 1 && args[0] === "--write") return "write";
  throw new Error(
    "usage: check-sdk-generated-types.mjs [--write]",
  );
}

const transcriptV2InterfaceNames = [
  "SessionTranscriptV2Message",
  "SessionTranscriptV2ActiveTurn",
  "SessionTranscriptV2TurnResult",
  "SessionTranscriptV2Result",
];

function extractJsonObjectInterface(sourceFile, interfaceName) {
  const declaration = sourceFile.statements.find(
    (statement) =>
      isInterfaceDeclaration(statement) &&
      statement.name.text === interfaceName,
  );
  if (declaration === undefined) {
    throw new Error(`missing runtime interface ${interfaceName}`);
  }
  const heritageTypes = declaration.heritageClauses?.flatMap(
    (clause) => clause.types,
  );
  if (
    heritageTypes?.length !== 1 ||
    heritageTypes[0]?.expression.getText(sourceFile) !== "JsonObject"
  ) {
    throw new Error(
      `runtime interface ${interfaceName} must extend JsonObject`,
    );
  }
  return declaration
    .getText(sourceFile)
    .replace("extends JsonObject", "extends TranscriptV2JsonObject");
}

function renderTranscriptV2Generated(runtimeProtocol) {
  const sourceFile = createSourceFile(
    paths.runtimeProtocol,
    normalizeLineEndings(runtimeProtocol),
    ScriptTarget.Latest,
    true,
  );
  const interfaces = transcriptV2InterfaceNames.map((interfaceName) =>
    extractJsonObjectInterface(sourceFile, interfaceName),
  );
  return `${[
    "// @generated from runtime/src/app-server/protocol/index.ts. Do not edit.",
    "// This file is automatically generated from the daemon protocol.",
    "// Verify with: npm --workspace=@tetsuo-ai/runtime run check:sdk-generated-types",
    "",
    "type TranscriptV2JsonPrimitive = string | number | boolean | null;",
    "type TranscriptV2JsonValue =",
    "  | TranscriptV2JsonPrimitive",
    "  | readonly TranscriptV2JsonValue[]",
    "  | TranscriptV2JsonObject;",
    "interface TranscriptV2JsonObject {",
    "  readonly [key: string]: TranscriptV2JsonValue | undefined;",
    "}",
    "",
    interfaces.join("\n\n"),
    "",
  ].join("\n")}`;
}

async function existingFileMode(filePath) {
  try {
    const metadata = await lstat(filePath);
    return metadata.isFile() ? metadata.mode & 0o777 : undefined;
  } catch (error) {
    if (error?.code === "ENOENT") return undefined;
    throw error;
  }
}

async function writeFileAtomically(filePath, contents) {
  const existingMode = await existingFileMode(filePath);
  const temporaryPath = `${filePath}.${process.pid}.${randomUUID()}.tmp`;
  let handle;
  try {
    handle = await open(temporaryPath, "wx", existingMode ?? 0o666);
    await handle.writeFile(contents, { encoding: "utf8" });
    if (existingMode !== undefined) {
      await handle.chmod(existingMode);
    }
    await handle.sync();
    await handle.close();
    handle = undefined;
    await rename(temporaryPath, filePath);
  } catch (error) {
    await handle?.close().catch(() => {});
    await unlink(temporaryPath).catch(() => {});
    throw error;
  }
}

export async function synchronizeTranscriptV2Generated({
  runtimeProtocolPath,
  generatedPath,
  write = false,
}) {
  const runtimeProtocol = await readFile(runtimeProtocolPath, "utf8");
  const expected = renderTranscriptV2Generated(runtimeProtocol);
  return synchronizeGeneratedFile({ generatedPath, expected, write });
}

export async function synchronizeSdkWireGenerated({
  runtimeProtocolPath,
  generatedPath,
  write = false,
}) {
  const expected = await renderSdkWireTypes(runtimeProtocolPath);
  return synchronizeGeneratedFile({ generatedPath, expected, write });
}

async function synchronizeGeneratedFile({ generatedPath, expected, write }) {
  let current;
  try {
    current = await readFile(generatedPath, "utf8");
  } catch (error) {
    if (!write || error?.code !== "ENOENT") throw error;
  }

  if (!write) {
    return {
      changed: false,
      matches: normalizeLineEndings(current) === expected,
      expected,
    };
  }

  if (current === expected) {
    return { changed: false, matches: true, expected };
  }

  await writeFileAtomically(generatedPath, expected);
  return { changed: true, matches: true, expected };
}

function appendWireParityFailures(failures, parity) {
  for (const [surface, methods] of Object.entries(parity.mismatches)) {
    expectCondition(
      failures,
      methods.length === 0,
      `${surface}: ${methods.join(", ")}`,
    );
  }
  for (const diagnostic of parity.diagnostics) {
    failures.push(`${diagnostic.file ?? "compiler"}: ${diagnostic.message}`);
  }
}

function reportSdkGeneratedTypesSuccess(mode) {
  const message = mode === "write"
    ? `regenerated SDK artifacts; run ${checkCommand} to verify wire parity`
    : "verified committed SDK types";
  process.stdout.write(`[sdk generated types] ${message}\n`);
}

async function main() {
  const mode = parseSdkGeneratedTypesMode(process.argv.slice(2));
  const transcriptV2Path = path.join(
    runtimeRoot,
    paths.packageTranscriptV2,
  );
  const [
    schemas,
    coreTypes,
    generated,
    packageWorkflowResult,
    transcriptV2,
    wire,
  ] = await Promise.all([
    readRuntimeFile(paths.schemas),
    readRuntimeFile(paths.coreTypes),
    readRuntimeFile(paths.generated),
    readRuntimeFile(paths.packageWorkflowResult),
    synchronizeTranscriptV2Generated({
      runtimeProtocolPath: path.join(runtimeRoot, paths.runtimeProtocol),
      generatedPath: transcriptV2Path,
      write: mode === "write",
    }),
    synchronizeSdkWireGenerated({
      runtimeProtocolPath: path.join(runtimeRoot, paths.runtimeProtocol),
      generatedPath: path.join(runtimeRoot, paths.packageWire),
      write: mode === "write",
    }),
  ]);
  if (mode === "write") {
    const displayPath = path
      .relative(path.dirname(runtimeRoot), transcriptV2Path)
      .split(path.sep)
      .join("/");
    process.stdout.write(
      transcriptV2.changed
        ? `[sdk generated types] wrote ${displayPath}\n`
        : `[sdk generated types] ${displayPath} is already current\n`,
    );
    process.stdout.write(
      `[sdk generated types] ${wire.changed ? "wrote" : "current"} ${paths.packageWire}\n`,
    );
  }
  const failures = [];
  const sources = [
    [paths.schemas, schemas],
    [paths.coreTypes, coreTypes],
    [paths.generated, generated],
  ];

  for (const [relativePath, source] of sources) {
    expectCondition(
      failures,
      !source.includes("generate-sdk-types.ts"),
      `${relativePath} still references the removed SDK type generator`,
    );
    expectCondition(
      failures,
      source.includes(checkCommand),
      `${relativePath} does not point at ${checkCommand}`,
    );
  }

  for (const fieldName of ["updatedPermissions", "permission_suggestions"]) {
    expectCondition(
      failures,
      schemas.includes(
        `${fieldName}: z.array(PermissionUpdateSchema()).optional()`,
      ),
      `${paths.schemas} no longer declares ${fieldName} as a PermissionUpdate array`,
    );
  }

  expectCondition(
    failures,
    !/(updatedPermissions|permission_suggestions)\?: \(\{/.test(generated),
    `${paths.generated} expanded a PermissionUpdate array as an object-union array`,
  );

  for (const marker of [
    "export const WorkflowHandoffOwnerSchema",
    "export const WorkflowHandoffArtifactSchema",
    "kind: z.literal('workflow_handoff')",
    "compatibility_epoch: z.literal('workflow_handoff.v1/state-schema.22')",
    "byte_length: z.number().int().min(0).max(16_777_216)",
    "token_count: z.number().int().min(0).max(131_072)",
  ]) {
    expectCondition(
      failures,
      schemas.includes(marker),
      `${paths.schemas} is missing workflow handoff marker ${marker}`,
    );
  }
  for (const marker of [
    "export const WorkflowStepOutcomeV2Schema",
    "export const WorkflowRunOutcomeV2Schema",
    "export const WorkflowRunResultV2Schema",
    "workflow_result_version: z.literal(2)",
    "manifest_format_version: z.literal(2)",
    "blocked_dependency_unknown",
    "unknown_outcome",
  ]) {
    expectCondition(
      failures,
      schemas.includes(marker),
      `${paths.schemas} is missing workflow result marker ${marker}`,
    );
  }
  for (const marker of [
    "export type WorkflowStepOutcomeV2",
    "export type WorkflowRunOutcomeV2",
    "export type WorkflowRunResultV2",
    "workflow_result_version: 2",
    "manifest_format_version: 2",
    "outcome: WorkflowRunOutcomeV2",
  ]) {
    expectCondition(
      failures,
      generated.includes(marker),
      `${paths.generated} is missing workflow result marker ${marker}`,
    );
  }
  for (const marker of [
    "export const AGENC_WORKFLOW_RESULT_VERSION = 2 as const",
    "export const AGENC_WORKFLOW_STEP_OUTCOMES_V2",
    "export const AGENC_WORKFLOW_RUN_OUTCOMES_V2",
    "export interface WorkflowRunResultV2",
    '"blocked_dependency_unknown"',
    '"unknown_outcome"',
  ]) {
    expectCondition(
      failures,
      packageWorkflowResult.includes(marker),
      `${paths.packageWorkflowResult} is missing workflow result marker ${marker}`,
    );
  }
  for (const marker of [
    "export type WorkflowHandoffOwner",
    "export type WorkflowHandoffArtifact",
    'kind: "workflow_handoff"',
    'compatibility_epoch: "workflow_handoff.v1/state-schema.22"',
    "digest: `sha256:${string}`",
  ]) {
    expectCondition(
      failures,
      generated.includes(marker),
      `${paths.generated} is missing workflow handoff marker ${marker}`,
    );
  }
  expectCondition(
    failures,
    countMatches(
      generated,
      /(updatedPermissions|permission_suggestions)\?: PermissionUpdate\[\]/g,
    ) === 6,
    `${paths.generated} should contain six generated PermissionUpdate[] fields`,
  );

  const duplicatedObjectProperty = generated.match(
    /^\s*([A-Za-z_]\w*\??): \{\n\s*\1: \{/m,
  );
  expectCondition(
    failures,
    duplicatedObjectProperty === null,
    `${paths.generated} contains adjacent duplicate object property ${duplicatedObjectProperty?.[1]}`,
  );

  expectCondition(
    failures,
    !schemas.includes("McpSdkServerConfig") &&
      !generated.includes("McpSdkServerConfig"),
    "committed SDK types reintroduced removed MCP surface McpSdkServerConfig",
  );

  expectCondition(
    failures,
    transcriptV2.matches,
    `${paths.packageTranscriptV2} is not the exact generated transcript.v2 mirror; regenerate it from ${paths.runtimeProtocol}`,
  );
  expectCondition(
    failures,
    wire.matches,
    `${paths.packageWire} is stale; run ${checkCommand} -- --write`,
  );

  if (mode === "check") {
    appendWireParityFailures(failures, checkSdkWireParity());
  }

  if (failures.length > 0) {
    process.stderr.write(
      `[sdk generated types] found ${failures.length} issue(s):\n- ${failures.join("\n- ")}\n`,
    );
    process.exitCode = 1;
    return;
  }

  reportSdkGeneratedTypesSuccess(mode);
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await main();
}
